#!/usr/bin/env python3
"""Generates the typed request layer of PVEKit from the Proxmox VE API schema.

    scripts/generate-pvekit-api.py            # (re)writes Packages/PVEKit/Sources/PVEKit/Generated
    scripts/generate-pvekit-api.py --check    # exits 1 if the committed files are out of date

Input: `Schema/pve-api-9.2.json` (see `scripts/import-pve-schema.py`). Works offline, uses only
the Python standard library and is deterministic (same input → byte-identical output).

For every path and HTTP method one `PVEAPI.<Name>` struct conforming to `PVEAPIRequest` is
emitted:

* path parameters and required parameters are non-optional `let`/`var` properties and form the
  initializer; optional parameters are `var`s defaulting to `nil`;
* `enum` parameters become nested `String` enums, `[n]` parameters (`net[n]`, `scsi[n]` …)
  become `[Int: String]` dictionaries, arrays repeat the key;
* schema descriptions are kept as doc comments;
* `Response` is a generated `Decodable` type when the schema lists properties (lenient decoding:
  numbers in strings, `0`/`1` booleans, unknown values never fail), `String` for string results,
  `EmptyResponse` for `null` and `JSONValue` otherwise.

Type names are the HTTP verb followed by the static path segments; a trailing parameter segment
adds `By<Parameter>`, e.g. `GET /nodes/{node}/qemu/{vmid}/status/current` →
`PVEAPI.GetNodesQemuStatusCurrent`, `DELETE /nodes/{node}/qemu/{vmid}/snapshot/{snapname}` →
`PVEAPI.DeleteNodesQemuSnapshotBySnapname`.

Output is split by top-level path (and by the next segment for `/nodes` and `/cluster`) to keep
files small and compile times reasonable.
"""
from __future__ import annotations

import json
import pathlib
import re
import sys
from dataclasses import dataclass, field

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "Schema" / "pve-api-9.2.json"
OUTPUT = ROOT / "Packages" / "PVEKit" / "Sources" / "PVEKit" / "Generated"

HEADER = """// Generated by scripts/generate-pvekit-api.py from Schema/pve-api-9.2.json — do not edit.
// pve-docs {commit} (pve-docs {version}).
"""

SWIFT_KEYWORDS = {
    "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func", "import", "init",
    "inout", "internal", "let", "open", "operator", "private", "precedencegroup", "protocol", "public",
    "rethrows", "static", "struct", "subscript", "typealias", "var", "break", "case", "catch",
    "continue", "default", "defer", "do", "else", "fallthrough", "for", "guard", "if", "in", "repeat",
    "return", "throw", "switch", "where", "while", "as", "false", "is", "nil", "self", "Self", "super",
    "throws", "true", "try", "Any", "Type", "Protocol", "some", "any",
}
# Names that would clash with the PVEAPIRequest requirements or generated helpers.
RESERVED_MEMBERS = {"path", "parameters", "method", "pathTemplate", "init"}
RESERVED_TYPES = {"Response", "Output", "Item", "CodingKeys", "Swift", "String", "Int", "Double", "Bool"}

VERBS = {"GET": "Get", "POST": "Post", "PUT": "Put", "DELETE": "Delete"}
SWIFT_METHOD = {"GET": ".get", "POST": ".post", "PUT": ".put", "DELETE": ".delete"}
MIN_GROUP_SIZE = 8  # endpoints; smaller sub-groups are merged into the top-level file
INDEXED = re.compile(r"^([A-Za-z][A-Za-z0-9_-]*)\[n\]$")


# MARK: - Naming

def words(name: str) -> list[str]:
    """Splits `query-url-metadata`, `CSRFPreventionToken`, `Datastore.Allocate` into words."""
    parts = re.split(r"[^A-Za-z0-9]+", name)
    result: list[str] = []
    for part in parts:
        if not part:
            continue
        # Split camel case and acronym runs: "CSRFPreventionToken" → CSRF, Prevention, Token.
        result.extend(re.findall(r"[A-Z]+(?=[A-Z][a-z]|[0-9]|$)|[A-Z]?[a-z]+|[A-Z]+|[0-9]+", part))
    return result


def upper_camel(name: str) -> str:
    ws = words(name)
    text = "".join(w[:1].upper() + w[1:] for w in ws) or "Value"
    if text[0].isdigit():
        text = "_" + text
    return text


def lower_camel(name: str) -> str:
    ws = words(name)
    if not ws:
        return "value"
    first = ws[0].lower()
    text = first + "".join(w[:1].upper() + w[1:] for w in ws[1:])
    if text[0].isdigit():
        text = "_" + text
    return text


def escape_identifier(name: str) -> str:
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def member_name(raw: str, taken: set[str]) -> str:
    name = lower_camel(raw)
    if name in RESERVED_MEMBERS:
        name += "Param"
    base, n = name, 2
    while name in taken:
        name = f"{base}{n}"
        n += 1
    taken.add(name)
    return name


def type_name(raw: str, taken: set[str]) -> str:
    name = upper_camel(raw)
    if name in RESERVED_TYPES or name in SWIFT_KEYWORDS:
        name += "Value"
    base, n = name, 2
    while name in taken:
        name = f"{base}{n}"
        n += 1
    taken.add(name)
    return name


def swift_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "").replace("\t", "\\t")
    return f'"{escaped}"'


def doc_lines(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    lines = []
    for line in str(text).replace("\r", "").strip().split("\n"):
        line = line.rstrip()
        lines.append(f"{indent}///" + (f" {line}" if line else ""))
    return lines


def request_type_name(path: str, method: str, include_all_params: bool = False) -> str:
    segments = [s for s in path.split("/") if s]
    name = VERBS[method]
    for index, segment in enumerate(segments):
        match = re.fullmatch(r"\{(.+)\}", segment)
        if match:
            if include_all_params or index == len(segments) - 1:
                name += "By" + upper_camel(match.group(1))
        else:
            name += upper_camel(segment)
    return name


def file_group(path: str) -> str:
    segments = [s for s in path.split("/") if s]
    if not segments:
        return "Root"
    top = upper_camel(segments[0])
    if segments[0] == "nodes" and len(segments) >= 3:
        return f"{top}+{upper_camel(segments[2])}"
    if segments[0] == "cluster" and len(segments) >= 2:
        return f"{top}+{upper_camel(segments[1])}"
    return top


# MARK: - Model

@dataclass
class Param:
    raw: str              # schema name (`net[n]` for indexed parameters)
    key: str              # wire name (`net` for indexed parameters)
    swift: str            # property name
    kind: str             # string | integer | number | boolean | array | indexed
    optional: bool
    in_path: bool
    schema: dict
    enum_type: str | None = None
    enum_values: list[str] = field(default_factory=list)
    item_kind: str = "string"

    @property
    def swift_type(self) -> str:
        if self.kind == "indexed":
            return "[Int: String]"
        if self.kind == "array":
            return f"[{scalar_swift(self.item_kind)}]"
        if self.enum_type:
            return self.enum_type
        return scalar_swift(self.kind)


def scalar_swift(kind: str) -> str:
    return {"integer": "Int", "number": "Double", "boolean": "Bool"}.get(kind, "String")


def param_kind(schema: dict) -> str:
    kind = schema.get("type")
    if kind in ("integer", "number", "boolean", "array"):
        return kind
    return "string"


def describe_param(schema: dict) -> list[str]:
    """Extra doc facts: default, range, length, format."""
    facts = []
    if "default" in schema:
        facts.append(f"Default: `{schema['default']}`.")
    lo, hi = schema.get("minimum"), schema.get("maximum")
    if lo is not None and hi is not None:
        facts.append(f"Range: {lo}…{hi}.")
    elif lo is not None:
        facts.append(f"Minimum: {lo}.")
    elif hi is not None:
        facts.append(f"Maximum: {hi}.")
    if isinstance(schema.get("format"), str):
        facts.append(f"Format: `{schema['format']}`.")
    elif isinstance(schema.get("format"), dict) and schema.get("typetext"):
        facts.append(f"Property string: `{schema['typetext']}`.")
    if schema.get("maxLength") is not None:
        facts.append(f"Max length: {schema['maxLength']}.")
    if schema.get("sensitive"):
        facts.append("Sensitive.")
    return facts


@dataclass
class ResponseProp:
    key: str
    swift: str
    swift_type: str       # String, Int, Double, Bool, JSONValue, [..], nested type name
    decode: str           # decoding expression using `c` and `Keys.<case>`
    description: str | None
    indexed_prefix: str | None = None


@dataclass
class ResponseType:
    name: str
    description: str | None
    props: list[ResponseProp]
    nested: list["ResponseType"]


class Generator:
    def __init__(self, document: dict):
        self.document = document
        self.source = document["source"]
        self.endpoints: list[tuple[str, str, dict]] = []
        for node in document["schema"]:
            self.walk(node)
        self.endpoints.sort(key=lambda e: (e[0], list(VERBS).index(e[1])))
        self.names = self.assign_names()

    def walk(self, node: dict) -> None:
        for method, info in sorted((node.get("info") or {}).items()):
            if method in VERBS:
                self.endpoints.append((node["path"], method, info))
        for child in node.get("children") or []:
            self.walk(child)

    def assign_names(self) -> dict[tuple[str, str], str]:
        names = {(p, m): request_type_name(p, m) for p, m, _ in self.endpoints}
        counts: dict[str, int] = {}
        for name in names.values():
            counts[name] = counts.get(name, 0) + 1
        for key, name in list(names.items()):
            if counts[name] > 1:
                names[key] = request_type_name(key[0], key[1], include_all_params=True)
        if len(set(names.values())) != len(names):
            duplicates = sorted({n for n in names.values() if list(names.values()).count(n) > 1})
            raise SystemExit(f"duplicate request type names: {duplicates}")
        return names

    # MARK: Parameters

    def params(self, path: str, info: dict, nested_types: set[str]) -> list[Param]:
        properties = (info.get("parameters") or {}).get("properties") or {}
        path_params = re.findall(r"\{([^}]+)\}", path)
        taken: set[str] = set()
        result: list[Param] = []
        rest = [k for k in properties if k not in path_params]
        # Path parameters, then required, then optional ones (each alphabetical).
        ordered = path_params + sorted(k for k in rest if not properties[k].get("optional")) \
            + sorted(k for k in rest if properties[k].get("optional"))
        for raw in ordered:
            schema = properties.get(raw, {"type": "string"})
            indexed = INDEXED.match(raw)
            key = indexed.group(1) if indexed else raw
            kind = "indexed" if indexed else param_kind(schema)
            param = Param(
                raw=raw,
                key=key,
                swift=member_name(key, taken),
                kind=kind,
                optional=(raw not in path_params) and bool(schema.get("optional")),
                in_path=raw in path_params,
                schema=schema,
            )
            if kind == "array":
                items = schema.get("items") or {}
                param.item_kind = param_kind(items) if items.get("type") != "array" else "string"
            values = schema.get("enum")
            if kind == "string" and isinstance(values, list) and values and all(isinstance(v, str) for v in values):
                param.enum_type = type_name(key, nested_types)
                param.enum_values = list(dict.fromkeys(values))
            result.append(param)
        return result

    # MARK: Responses

    def response(self, returns: dict, owner: str) -> tuple[str, ResponseType | None]:
        kind = returns.get("type")
        if returns.get("properties"):
            return "Output", self.object_type("Output", returns)
        if kind == "array":
            items = returns.get("items") or {}
            if items.get("properties"):
                return "[Item]", self.object_type("Item", items)
            return "JSONValue", None
        if kind == "string":
            return "String", None
        if kind == "null":
            return "EmptyResponse", None
        return "JSONValue", None

    def object_type(self, name: str, schema: dict) -> ResponseType:
        taken_members: set[str] = set()
        taken_types: set[str] = {name}
        props: list[ResponseProp] = []
        nested: list[ResponseType] = []
        for key in sorted(schema.get("properties") or {}):
            prop = schema["properties"][key]
            indexed = INDEXED.match(key)
            if indexed:
                prefix = indexed.group(1)
                swift = member_name(prefix, taken_members)
                props.append(ResponseProp(prefix, swift, "[Int: String]", "", prop.get("description"), indexed_prefix=prefix))
                continue
            swift = member_name(key, taken_members)
            swift_type, decode, child = self.prop_type(key, prop, taken_types)
            if child:
                nested.append(child)
            props.append(ResponseProp(key, swift, swift_type, decode, prop.get("description")))
        return ResponseType(name, schema.get("description"), props, nested)

    def prop_type(self, key: str, prop: dict, taken_types: set[str]) -> tuple[str, str, ResponseType | None]:
        kind = prop.get("type")
        if prop.get("properties"):
            child = self.object_type(type_name(key, taken_types), prop)
            return child.name, f"try? c.decodeIfPresent({child.name}.self, forKey: {{k}})", child
        if kind == "array":
            items = prop.get("items") or {}
            if items.get("properties"):
                child = self.object_type(type_name(key + "-item", taken_types), items)
                return f"[{child.name}]", f"try? c.decodeIfPresent([{child.name}].self, forKey: {{k}})", child
            item_kind = items.get("type")
            if item_kind in ("string", "integer", "number", "boolean"):
                element = scalar_swift(item_kind)
                return f"[{element}]", f"c.lenientArray({element}.self, forKey: {{k}})", None
            return "[JSONValue]", "try? c.decodeIfPresent([JSONValue].self, forKey: {k})", None
        if kind == "string":
            return "String", "c.flexibleString({k})", None
        if kind == "integer":
            return "Int", "c.flexibleInt({k})", None
        if kind == "number":
            return "Double", "c.flexibleDouble({k})", None
        if kind == "boolean":
            return "Bool", "c.flexibleBool({k})", None
        return "JSONValue", "try? c.decodeIfPresent(JSONValue.self, forKey: {k})", None

    # MARK: Emission

    def emit_response_type(self, t: ResponseType, indent: str) -> list[str]:
        out = doc_lines(t.description, indent)
        out.append(f"{indent}public struct {t.name}: Decodable, Sendable, Hashable {{")
        inner = indent + "    "
        for p in t.props:
            out += doc_lines(p.description, inner)
            out.append(f"{inner}public var {escape_identifier(p.swift)}: {p.swift_type}{'' if p.indexed_prefix else '?'}")
        plain = [p for p in t.props if not p.indexed_prefix]
        indexed = [p for p in t.props if p.indexed_prefix]
        if t.props:
            out.append("")
        out.append(f"{inner}public init(from decoder: any Decoder) throws {{")
        body = inner + "    "
        if plain:
            out.append(f"{body}let c = try decoder.container(keyedBy: AnyCodingKey.self)")
            for p in plain:
                expr = p.decode.replace("{k}", f"AnyCodingKey({swift_string(p.key)})")
                out.append(f"{body}{escape_identifier(p.swift)} = {expr}")
        if indexed:
            out.append(f"{body}let all = try decoder.container(keyedBy: AnyCodingKey.self)")
            for p in indexed:
                out.append(f"{body}{escape_identifier(p.swift)} = all.indexedStrings(prefix: {swift_string(p.indexed_prefix)})")
        if not t.props:
            out.append(f"{body}_ = decoder")
        out.append(f"{inner}}}")
        for child in t.nested:
            out.append("")
            out += self.emit_response_type(child, inner)
        out.append(f"{indent}}}")
        return out

    def emit_enum(self, param: Param, indent: str) -> list[str]:
        out = doc_lines(param.schema.get("description"), indent)
        out.append(f"{indent}public enum {param.enum_type}: String, Sendable, Hashable, CaseIterable, Codable, PVEParameterValue {{")
        taken: set[str] = set()
        for value in param.enum_values:
            case = lower_camel(value) if words(value) else "empty"
            base, n = case, 2
            while case in taken:
                case = f"{base}{n}"
                n += 1
            taken.add(case)
            out.append(f"{indent}    case {escape_identifier(case)} = {swift_string(value)}")
        out.append(f"{indent}}}")
        return out

    def emit_request(self, path: str, method: str, info: dict) -> list[str]:
        name = self.names[(path, method)]
        nested_types: set[str] = set()
        params = self.params(path, info, nested_types)
        response_type, response_model = self.response(info.get("returns") or {}, name)
        indent = "    "
        out: list[str] = []
        out.append(f"{indent}/// `{method} {path}`")
        if info.get("description"):
            out.append(f"{indent}///")
            out += doc_lines(info["description"], indent)
        out.append(f"{indent}public struct {name}: PVEAPIRequest, Hashable {{")
        inner = indent + "    "
        out.append(f"{inner}public typealias Response = {response_type}")
        out.append(f"{inner}public static let method: HTTPMethod = {SWIFT_METHOD[method]}")
        out.append(f"{inner}public static let pathTemplate = {swift_string(path)}")
        out.append(f"{inner}public static let schemaName = {swift_string(info.get('name', ''))}")
        for p in params:
            out.append("")
            out += doc_lines(p.schema.get("description"), inner)
            facts = describe_param(p.schema)
            if facts:
                if p.schema.get("description"):
                    out.append(f"{inner}///")
                out.append(f"{inner}/// " + " ".join(facts))
            if p.kind == "indexed":
                out.append(f"{inner}/// Sent as `{p.key}0`, `{p.key}1`, … (`{p.raw}` in the schema).")
                out.append(f"{inner}public var {escape_identifier(p.swift)}: [Int: String] = [:]")
            elif p.kind == "array" and p.optional:
                out.append(f"{inner}public var {escape_identifier(p.swift)}: {p.swift_type}?")
            elif p.optional:
                out.append(f"{inner}public var {escape_identifier(p.swift)}: {p.swift_type}?")
            else:
                out.append(f"{inner}public var {escape_identifier(p.swift)}: {p.swift_type}")

        required = [p for p in params if not p.optional and p.kind != "indexed"]
        out.append("")
        signature = ", ".join(f"{escape_identifier(p.swift)}: {p.swift_type}" for p in required)
        out.append(f"{inner}public init({signature}) {{")
        for p in required:
            out.append(f"{inner}    self.{p.swift.strip('`')} = {escape_identifier(p.swift)}")
        out.append(f"{inner}}}")

        # path
        out.append("")
        segments = []
        by_key = {p.raw: p for p in params}
        for segment in [s for s in path.split("/") if s]:
            match = re.fullmatch(r"\{(.+)\}", segment)
            if match:
                p = by_key[match.group(1)]
                segments.append(f"{escape_identifier(p.swift)}.parameterValue")
            else:
                segments.append(swift_string(segment))
        if segments:
            out.append(f"{inner}public var path: String {{ PathBuilder.path({', '.join(segments)}) }}")
        else:
            out.append(f'{inner}public var path: String {{ "/" }}')

        # parameters
        out.append("")
        others = [p for p in params if not p.in_path]
        if not others:
            out.append(f"{inner}public var parameters: [(String, String)] {{ [] }}")
        else:
            out.append(f"{inner}public var parameters: [(String, String)] {{")
            out.append(f"{inner}    var result: [(String, String)] = []")
            for p in others:
                ident = escape_identifier(p.swift)
                key = swift_string(p.key)
                if p.kind == "indexed":
                    out.append(f"{inner}    result.appendIndexed({key}, {ident})")
                elif p.kind == "array":
                    if p.optional:
                        out.append(f"{inner}    for value in {ident} ?? [] {{ result.append(({key}, value.parameterValue)) }}")
                    else:
                        out.append(f"{inner}    for value in {ident} {{ result.append(({key}, value.parameterValue)) }}")
                elif p.optional:
                    out.append(f"{inner}    if let value = {ident} {{ result.append(({key}, value.parameterValue)) }}")
                else:
                    out.append(f"{inner}    result.append(({key}, {ident}.parameterValue))")
            out.append(f"{inner}    return result")
            out.append(f"{inner}}}")

        for p in params:
            if p.enum_type:
                out.append("")
                out += self.emit_enum(p, inner)
        if response_model:
            out.append("")
            out += self.emit_response_type(response_model, inner)
        out.append(f"{indent}}}")
        return out

    def files(self) -> dict[str, str]:
        groups: dict[str, list[tuple[str, str, dict]]] = {}
        for path, method, info in self.endpoints:
            groups.setdefault(file_group(path), []).append((path, method, info))
        # Small sub-groups go back into their top-level file.
        for group in [g for g in groups if "+" in g and len(groups[g]) < MIN_GROUP_SIZE]:
            groups.setdefault(group.split("+")[0], []).extend(groups.pop(group))
        for endpoints in groups.values():
            endpoints.sort(key=lambda e: (e[0], list(VERBS).index(e[1])))
        header = HEADER.format(commit=self.source["commit"], version=self.source["pveDocsVersion"])
        result: dict[str, str] = {}
        for group, endpoints in sorted(groups.items()):
            lines = [header, "import Foundation", "", "extension PVEAPI {"]
            for index, (path, method, info) in enumerate(endpoints):
                if index:
                    lines.append("")
                lines += self.emit_request(path, method, info)
            lines.append("}")
            result[f"PVEAPI+{group}.swift"] = "\n".join(lines) + "\n"
        # Index of every request type, handy for tests and tooling.
        index = [header, "import Foundation", "", "extension PVEAPI {",
                 "    /// Every generated request type with its method and path template.",
                 "    public static let allRequests: [any PVEAPIRequest.Type] = ["]
        for path, method, _ in self.endpoints:
            index.append(f"        {self.names[(path, method)]}.self,")
        index += ["    ]", "", f"    /// pve-docs commit the schema was taken from.",
                  f"    public static let schemaCommit = {swift_string(self.source['commit'])}",
                  f"    /// pve-docs version of that commit.",
                  f"    public static let schemaVersion = {swift_string(self.source['pveDocsVersion'])}",
                  "}"]
        result["PVEAPI+Index.swift"] = "\n".join(index) + "\n"
        return result


def main() -> int:
    check = "--check" in sys.argv[1:]
    document = json.loads(SCHEMA.read_text(encoding="utf-8"))
    files = Generator(document).files()
    if check:
        existing = {p.name: p.read_text(encoding="utf-8") for p in OUTPUT.glob("*.swift")} if OUTPUT.exists() else {}
        stale = sorted(set(existing) ^ set(files)) + sorted(n for n in files if n in existing and existing[n] != files[n])
        if stale:
            print("Generated PVEKit sources are out of date; run scripts/generate-pvekit-api.py:", file=sys.stderr)
            for name in stale:
                print(f"  {name}", file=sys.stderr)
            return 1
        print(f"Generated sources up to date ({len(files)} files).")
        return 0
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for old in OUTPUT.glob("*.swift"):
        if old.name not in files:
            old.unlink()
    for name, text in files.items():
        target = OUTPUT / name
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            target.write_text(text, encoding="utf-8")
    total = sum(text.count("\n") for text in files.values())
    print(f"Wrote {len(files)} files ({total} lines) to {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
